#include <LibCrypto/Authentication/KMAC.h>
#include <LibCrypto/Hash/SHAKE.h>
#include <string.h>

static bool matches(ErrorOr<ByteBuffer> result, u8 const* expected, size_t expected_size)
{
    if (result.is_error())
        return false;
    auto output = result.release_value();
    return output.size() == expected_size && memcmp(output.data(), expected, expected_size) == 0;
}

int main()
{
    static constexpr u8 key[] {
        0x40, 0x41, 0x42, 0x43, 0x44, 0x45, 0x46, 0x47,
        0x48, 0x49, 0x4a, 0x4b, 0x4c, 0x4d, 0x4e, 0x4f,
        0x50, 0x51, 0x52, 0x53, 0x54, 0x55, 0x56, 0x57,
        0x58, 0x59, 0x5a, 0x5b, 0x5c, 0x5d, 0x5e, 0x5f,
    };
    static constexpr u8 message[] { 0x00, 0x01, 0x02, 0x03 };
    static constexpr u8 kmac_expected[] {
        0xe5, 0x78, 0x0b, 0x0d, 0x3e, 0xa6, 0xf7, 0xd3,
        0xa4, 0x29, 0xc5, 0x70, 0x6a, 0xa4, 0x3a, 0x00,
        0xfa, 0xdb, 0xd7, 0xd4, 0x96, 0x28, 0x83, 0x9e,
        0x31, 0x87, 0x24, 0x3f, 0x45, 0x6e, 0xe1, 0x4e,
    };
    static constexpr u8 cshake_expected[] {
        0xc1, 0xc3, 0x69, 0x25, 0xb6, 0x40, 0x9a, 0x04,
        0xf1, 0xb5, 0x04, 0xfc, 0xbc, 0xa9, 0xd8, 0x2b,
        0x40, 0x17, 0x27, 0x7c, 0xb5, 0xed, 0x2b, 0x20,
        0x65, 0xfc, 0x1d, 0x38, 0x14, 0xd5, 0xaa, 0xf5,
    };
    static constexpr u8 kmac256_expected[] {
        0x2e, 0xbd, 0x16, 0x22, 0xde, 0x2d, 0xe4, 0x41,
        0x74, 0xe3, 0x47, 0x72, 0x06, 0x06, 0x0d, 0x7f,
        0x64, 0x48, 0x9a, 0x63, 0x9b, 0x75, 0x45, 0x64,
        0x91, 0x32, 0x31, 0x76, 0x09, 0xfa, 0x21, 0x4f,
        0x4c, 0x8a, 0xc9, 0x06, 0x30, 0xfb, 0x4c, 0x75,
        0x7f, 0xba, 0x07, 0x4b, 0x15, 0x18, 0x6f, 0xe4,
        0x52, 0xae, 0x71, 0xb6, 0xa1, 0xe4, 0x43, 0xbf,
        0x54, 0x05, 0x9e, 0x09, 0x0c, 0x11, 0xae, 0x20,
    };
    static constexpr u8 cshake256_expected[] {
        0xd0, 0x08, 0x82, 0x8e, 0x2b, 0x80, 0xac, 0x9d,
        0x22, 0x18, 0xff, 0xee, 0x1d, 0x07, 0x0c, 0x48,
        0xb8, 0xe4, 0xc8, 0x7b, 0xff, 0x32, 0xc9, 0x69,
        0x9d, 0x5b, 0x68, 0x96, 0xee, 0xe0, 0xed, 0xd1,
        0x64, 0x02, 0x0e, 0x2b, 0xe0, 0x56, 0x08, 0x58,
        0xd9, 0xc0, 0x0c, 0x03, 0x7e, 0x34, 0xa9, 0x69,
        0x37, 0xc5, 0x61, 0xa7, 0x4c, 0x41, 0x2b, 0xb4,
        0xc7, 0x46, 0x46, 0x95, 0x27, 0x28, 0x1c, 0x8c,
    };
    static constexpr u8 shake_prefix[] {
        0x7f, 0x9c, 0x2b, 0xa4, 0xe8, 0x8f, 0x82, 0x7d,
        0x61, 0x60, 0x45, 0x50, 0x76, 0x05, 0x85, 0x3e,
        0xd7, 0x3b, 0x80, 0x93, 0xf6, 0xef, 0xbc, 0x88,
        0xeb, 0x1a, 0x6e, 0xac, 0xfa, 0x66, 0xef, 0x26,
    };
    static constexpr char customization[] = "Email Signature";

    Crypto::Authentication::KMAC kmac { Crypto::Authentication::KMACKind::KMAC128 };
    if (!matches(kmac.sign(key, message, 256, {}), kmac_expected, sizeof(kmac_expected)))
        return 1;

    Crypto::Authentication::KMAC kmac256 { Crypto::Authentication::KMACKind::KMAC256 };
    if (!matches(kmac256.sign(key, message, 512, {}), kmac256_expected, sizeof(kmac256_expected)))
        return 2;

    Crypto::Hash::SHAKE cshake { Crypto::Hash::SHAKEKind::CSHAKE128 };
    if (!matches(cshake.digest(message, 256, ReadonlyBytes { reinterpret_cast<u8 const*>(customization), sizeof(customization) - 1 }, {}), cshake_expected, sizeof(cshake_expected)))
        return 3;

    Crypto::Hash::SHAKE cshake256 { Crypto::Hash::SHAKEKind::CSHAKE256 };
    if (!matches(cshake256.digest(message, 512, ReadonlyBytes { reinterpret_cast<u8 const*>(customization), sizeof(customization) - 1 }, {}), cshake256_expected, sizeof(cshake256_expected)))
        return 4;

    auto shake_result = cshake.digest({}, 1608, {}, {});
    if (shake_result.is_error())
        return 5;
    auto shake_output = shake_result.release_value();
    if (shake_output.size() != 201
        || memcmp(shake_output.data(), shake_prefix, sizeof(shake_prefix)) != 0
        || shake_output[135] != 0x56 || shake_output[136] != 0x23
        || shake_output[167] != 0xa9 || shake_output[168] != 0x76
        || shake_output[199] != 0x77 || shake_output[200] != 0x32)
        return 6;

    return 0;
}
